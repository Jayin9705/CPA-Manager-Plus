// Migrate applies the PostgreSQL core schema while holding a session-scoped
// advisory lock. Each version is committed atomically and recorded only after
// all of its DDL succeeds.
func Migrate(ctx context.Context, db *sql.DB, schema string) (returnErr error) {
	if db == nil {
		return errors.New("postgres core database is required")
	}
	conn, err := db.Conn(ctx)
	if err != nil {
		return fmt.Errorf("acquire postgres core migration connection: %w", err)
	}
	defer conn.Close()

	lockName := "cpamp-core-schema:" + schema
	if _, err := conn.ExecContext(ctx, `select pg_advisory_lock(hashtext($1))`, lockName); err != nil {
		return fmt.Errorf("acquire postgres core migration lock: %w", err)
	}
	defer func() {
		unlockCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if _, err := conn.ExecContext(unlockCtx, `select pg_advisory_unlock(hashtext($1))`, lockName); err != nil && returnErr == nil {
			returnErr = fmt.Errorf("release postgres core migration lock: %w", err)
		}
	}()

	if _, err := conn.ExecContext(ctx, `create table if not exists `+schemaVersionTable+` (
		version integer primary key,
		applied_at_ms bigint not null
	)`); err != nil {
		return fmt.Errorf("create postgres core schema version table: %w", err)
	}

	var currentVersion int
	if err := conn.QueryRowContext(ctx, `select coalesce(max(version), 0) from `+schemaVersionTable).Scan(&currentVersion); err != nil {
		return fmt.Errorf("read postgres core schema version: %w", err)
	}
	latestVersion := coreSchemaMigrations[len(coreSchemaMigrations)-1].version
	if currentVersion > latestVersion {
		return fmt.Errorf("postgres core schema version %d is newer than supported version %d", currentVersion, latestVersion)
	}

	for _, migration := range coreSchemaMigrations {
		if migration.version <= currentVersion {
			continue
		}
		tx, err := conn.BeginTx(ctx, nil)
		if err != nil {
			return fmt.Errorf("begin postgres core schema migration %d: %w", migration.version, err)
		}
		for _, statement := range migration.statements {
			if _, err := tx.ExecContext(ctx, statement); err != nil {
				_ = tx.Rollback()
				return fmt.Errorf("apply postgres core schema migration %d: %w", migration.version, err)
			}
		}
		if _, err := tx.ExecContext(ctx, `insert into `+schemaVersionTable+` (version, applied_at_ms) values ($1, $2)`, migration.version, time.Now().UnixMilli()); err != nil {
			_ = tx.Rollback()
			return fmt.Errorf("record postgres core schema migration %d: %w", migration.version, err)
		}
		if err := tx.Commit(); err != nil {
			return fmt.Errorf("commit postgres core schema migration %d: %w", migration.version, err)
		}
		currentVersion = migration.version
	}
	return nil
}
