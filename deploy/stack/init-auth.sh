#!/bin/sh
set -eu

postgres_password="$(tr -d '\r\n' </run/secrets/postgres_password)"
admin_password="$(tr -d '\r\n' </run/secrets/cpamp_admin_password)"

if [ -z "$postgres_password" ] || [ -z "$admin_password" ] || [ -z "${CPAMP_ADMIN_EMAIL:-}" ]; then
  printf '%s\n' 'PostgreSQL password, administrator email, and administrator password are required.' >&2
  exit 1
fi

export PGPASSWORD="$postgres_password"
psql --set=ON_ERROR_STOP=1 \
  --set=admin_email="$CPAMP_ADMIN_EMAIL" \
  --set=admin_password="$admin_password" <<'SQL'
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS cpamp_auth;

CREATE TABLE IF NOT EXISTS cpamp_auth.admins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  password_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS cpamp_admins_email_ci
  ON cpamp_auth.admins (lower(btrim(email)));

WITH updated AS (
  UPDATE cpamp_auth.admins
  SET password_hash = CASE
        WHEN password_hash = crypt(:'admin_password', password_hash) THEN password_hash
        ELSE crypt(:'admin_password', gen_salt('bf', 12))
      END,
      active = true,
      updated_at = now()
  WHERE lower(btrim(email)) = lower(btrim(:'admin_email'))
  RETURNING id
)
INSERT INTO cpamp_auth.admins (email, password_hash, active)
SELECT :'admin_email', crypt(:'admin_password', gen_salt('bf', 12)), true
WHERE NOT EXISTS (SELECT 1 FROM updated);

CREATE OR REPLACE VIEW cpamp_auth.active_admins AS
SELECT id, email, password_hash
FROM cpamp_auth.admins
WHERE active;
SQL

unset PGPASSWORD postgres_password admin_password
printf '%s\n' 'Administrator authentication schema is ready.'
